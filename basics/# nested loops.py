# nested loops
# means loops inside loops
for x in range(1,5):
    for y in range(1,5):
        print(f"({x} , {y})")\
        
# here we have two loops, the outer loop iterates through the values of x from 1 to 4, and for each value of x, the inner loop iterates through the values of y from 1 to 4. The print statement inside the inner loop prints the current values of x and y in a tuple format.